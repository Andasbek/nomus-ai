"""Red-flag детектор признаков принудительного труда (FR-23, §8.3 ТЗ).

Двухступенчатый: быстрые ключевые слова + (опционально) LLM-классификатор.
Ключевые слова срабатывают всегда, даже при недоступности LLM.
"""

import re

# Триггер → человекочитаемое название признака
KEYWORD_TRIGGERS: dict[str, str] = {
    r"паспорт\w*\s+(забрал|забрали|отобрал|отобрали|изъял|изъяли|не отда|удерж)": "изъятие документов",
    r"(забрал|забрали|отобрал|отобрали|изъял|изъяли)\s+(у меня\s+)?(паспорт|документ)": "изъятие документов",
    r"не\s+(отдают|отдаёт|отдает|возвращают)\s+(паспорт|документ)": "изъятие документов",
    r"не\s+(выпускают|разрешают выходить|даю?т выйти|могу уйти|отпускают)": "ограничение свободы",
    r"(запрещают|запретил\w*)\s+(покидать|выходить|уходить)": "ограничение свободы",
    r"держат\s+(взаперти|под замком|силой)": "ограничение свободы",
    r"работа\w*\s+(бесплатно|без оплаты|за еду|за жильё|за жилье)": "неоплачиваемый труд",
    r"(не платят|не заплатил\w*).{0,40}(угрожа|грозит|грозят)": "труд под угрозой",
    r"(угрожа\w+|запугива\w+)\s+(мне|нам|депортацией|полицией|расправой)": "угрозы",
    r"долг\w*\s+(отрабатыва|отработа)": "долговая кабала",
    r"(вычитают|удерживают|высчитывают)\s+за\s+(жильё|жилье|еду|проживание|дорогу|билет)": "долговая кабала",
    r"продал\w*\s+(меня|нас)": "торговля людьми",
}


def detect_red_flags(text: str) -> list[str]:
    """Возвращает список сработавших признаков (пустой = нет red-flag)."""
    low = text.lower()
    found: list[str] = []
    for pattern, label in KEYWORD_TRIGGERS.items():
        if re.search(pattern, low) and label not in found:
            found.append(label)
    return found


LLM_CLASSIFIER_PROMPT = """Ты — классификатор признаков принудительного труда.
Проанализируй сообщение трудового мигранта и определи, есть ли признаки:
изъятие документов, ограничение свободы передвижения, долговая кабала,
неоплачиваемый труд под угрозой, удержания «за жильё и еду» сверх зарплаты.

Верни строго JSON: {"red_flag": true/false, "triggers": ["..."]}
Если признаков нет — {"red_flag": false, "triggers": []}."""


async def detect_red_flags_llm(text: str, client) -> list[str]:
    """LLM-классификатор (вторая ступень). client — AsyncOpenAI. Ошибки глотаем."""
    import json

    from nomus.config import settings

    try:
        resp = await client.chat.completions.create(
            model=settings.openai_model,
            temperature=0,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": LLM_CLASSIFIER_PROMPT},
                {"role": "user", "content": text[:1000]},
            ],
            timeout=8,
        )
        data = json.loads(resp.choices[0].message.content)
        if data.get("red_flag"):
            return [str(t) for t in data.get("triggers", [])] or ["признаки принудительного труда"]
    except Exception:
        pass
    return []
