"""Query Rewriter (FR-11, §6.1 п.3): разговорный текст → юридический запрос.

Переформулировка учитывает правовой режим пользователя: для граждан ЕАЭС и
остальных релевантны разные НПА, и запрос без этого сигнала уходит в общие
миграционные нормы.
"""

from nomus.schemas import CitizenshipProfile

REWRITER_PROMPT = """Ты переформулируешь житейское описание проблемы трудового мигранта
в Казахстане в короткий юридический поисковый запрос по законодательству РК.

Правила:
- Используй юридическую терминологию: «невыплата заработной платы», «расторжение
  трудового договора», «разрешение на работу», «изъятие документа, удостоверяющего
  личность» и т.п.
- Перечисли все правовые аспекты через запятую. Без пояснений, только сам запрос.
- Не добавляй фактов, которых нет в сообщении.

Пример.
Вход: «мне не платят 3 месяца, паспорт забрали»
Выход: «невыплата заработной платы, сроки выплаты заработной платы,
ответственность работодателя за задержку зарплаты, изъятие документа,
удостоверяющего личность»"""

REGIME_HINTS = {
    CitizenshipProfile.EAEU: (
        "\n\nПРАВОВОЙ РЕЖИМ ПОЛЬЗОВАТЕЛЯ: гражданин государства — члена ЕАЭС.\n"
        "Если вопрос касается допуска к работе, разрешений, статуса или прав работника,\n"
        "добавь в запрос термины: «трудящийся государства-члена ЕАЭС», «Договор о ЕАЭС»,\n"
        "«трудовая деятельность без разрешения», «права трудящегося государства-члена»."
    ),
    CitizenshipProfile.NON_EAEU: (
        "\n\nПРАВОВОЙ РЕЖИМ ПОЛЬЗОВАТЕЛЯ: гражданин государства вне ЕАЭС.\n"
        "Если вопрос касается допуска к работе или статуса, добавь в запрос термины:\n"
        "«разрешение на работу иностранному работнику», «привлечение иностранной\n"
        "рабочей силы», «трудовой иммигрант»."
    ),
}


async def rewrite_query(
    text: str, client, citizenship: CitizenshipProfile | None = None
) -> str:
    """Возвращает юридический запрос; при ошибке LLM — исходный текст (degradation)."""
    from nomus.config import settings

    system = REWRITER_PROMPT + REGIME_HINTS.get(citizenship, "")
    try:
        resp = await client.chat.completions.create(
            model=settings.openai_model,
            temperature=0,
            messages=[
                {"role": "system", "content": system},
                {"role": "user", "content": text[:1000]},
            ],
            timeout=10,
        )
        rewritten = (resp.choices[0].message.content or "").strip()
        return rewritten or text
    except Exception:
        return text
